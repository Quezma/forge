#!/usr/bin/env bash
# Global agent rules: compose_rules / write_rules and the module hooks around them.
RULES_MARK="claude-setup:rules"

stub_rules() {
  d="$HOME/stub-rules"; mkdir -p "$d"
  printf '## A\nrule a\n' >"$d/a.md"
  printf '## B\nrule b\n' >"$d/b.md"
  export SETUP_RULES_DIR="$d"
}

seed_claude() {
  mkdir -p "$HOME/.claude"
  printf '# mine\n<!-- other:start -->\nkeep\n<!-- other:end -->\ntail line\n' >"$HOME/.claude/CLAUDE.md"
}

test_compose_rules_orders_modules_and_skips_missing_files() {
  . "$REPO/lib/common.sh"; stub_rules
  out="$(compose_rules b nofile a)"
  assert_eq "$(printf '%s\n' "$out" | sed -n 1p)" "<!-- Generated by claude-setup from rules/*.md; edit the repo, then re-run ./setup. -->"
  case "$out" in *"rule b"*"rule a"*) ;; *) echo "bad order: $out" >&2; return 1 ;; esac
  assert_absent "$out" nofile
  assert_eq "$(compose_rules nofile)" ""
}

test_write_rules_is_idempotent_and_preserves_outside_content() {
  . "$REPO/lib/common.sh"; stub_rules; seed_claude
  before="$(cat "$HOME/.claude/CLAUDE.md")"
  write_rules a b
  cp "$HOME/.claude/CLAUDE.md" "$HOME/first"
  write_rules a b
  cmp "$HOME/first" "$HOME/.claude/CLAUDE.md"
  assert_eq "$(grep -c "$RULES_MARK:start" "$HOME/.claude/CLAUDE.md")" "1"
  assert_eq "$(sed -n '1,5p' "$HOME/.claude/CLAUDE.md")" "$(printf '%s\n' "$before" | sed -n '1,5p')"
  assert_contains "$(cat "$HOME/.claude/CLAUDE.md")" "tail line"
  write_rules a # shrink: b's rules go away, outside text stays
  assert_absent "$(cat "$HOME/.claude/CLAUDE.md")" "rule b"
  assert_contains "$(cat "$HOME/.claude/CLAUDE.md")" "rule a"
  assert_contains "$(cat "$HOME/.claude/CLAUDE.md")" "keep"
}

test_write_rules_codex_only_when_codex_home_exists() {
  . "$REPO/lib/common.sh"; stub_rules
  has() { return 1; }
  write_rules a
  [ ! -e "$HOME/.codex" ]
  mkdir "$HOME/.codex"
  write_rules a
  assert_contains "$(cat "$HOME/.codex/AGENTS.md")" "rule a"
}

test_write_rules_removes_block_when_no_rules() {
  . "$REPO/lib/common.sh"; stub_rules; seed_claude
  write_rules a
  write_rules nofile
  assert_absent "$(cat "$HOME/.claude/CLAUDE.md")" "$RULES_MARK"
  assert_absent "$(cat "$HOME/.claude/CLAUDE.md")" "rule a"
  assert_contains "$(cat "$HOME/.claude/CLAUDE.md")" "tail line"
  rm "$HOME/.claude/CLAUDE.md"
  write_rules nofile # no file, nothing to remove: must not create one
  [ ! -e "$HOME/.claude/CLAUDE.md" ]
}

test_write_rules_dry_run_writes_nothing() {
  . "$REPO/lib/common.sh"; stub_rules
  DRY_RUN=1
  out="$(write_rules a b)"
  assert_contains "$out" "+ write rules block -> $HOME/.claude/CLAUDE.md (a b)"
  [ ! -e "$HOME/.claude" ]
}

test_setup_rules_cover_selected_and_installed_but_not_failed() {
  stub_rules
  m="$HOME/mods"; mkdir -p "$m"
  printf '## C\nrule c\n' >"$SETUP_RULES_DIR/c.md"
  printf '## Bad\nrule bad\n' >"$SETUP_RULES_DIR/bad.md"
  mk() { # name order status install-body
    printf 'MODULE_NAME=%s; MODULE_DESC=s; MODULE_DEFAULT=off; MODULE_DEPS=""\n%s_status() { echo %s; }\n%s_install() { %s; }\n' "$1" "$1" "$3" "$1" "$4" >"$m/$2-$1.sh"
  }
  mk a 10 missing true; mk bad 20 missing false; mk c 30 installed true; mk b 40 missing true
  rc=0; SETUP_MODULES_DIR="$m" "$REPO/setup" --only a,bad >/dev/null 2>&1 || rc=$?
  [ "$rc" -ne 0 ]
  got="$(cat "$HOME/.claude/CLAUDE.md")"
  assert_contains "$got" "rule a"
  assert_contains "$got" "rule c"   # installed earlier, not selected now
  assert_absent "$got" "rule bad"
  assert_absent "$got" "rule b"
}

test_setup_dry_run_prints_rules_line_and_writes_no_rules() {
  out="$("$REPO/setup" --only react-atlas,qa-engineer --dry-run)"
  assert_contains "$out" "+ write rules block -> $HOME/.claude/CLAUDE.md"
  [ ! -e "$HOME/.claude" ]
}

test_real_rules_files_start_with_heading_and_stay_short() {
  for f in react-atlas ex-atlas qa-engineer; do
    case "$(sed -n 1p "$REPO/rules/$f.md")" in "## "*) ;; *) echo "$f: no heading" >&2; return 1 ;; esac
    [ "$(wc -l <"$REPO/rules/$f.md")" -le 25 ] || { echo "$f too long" >&2; return 1; }
  done
  grep -q 'mix ex_atlas.install' "$REPO/rules/ex-atlas.md"
}

test_react_atlas_install_migrates_old_block_away() {
  . "$REPO/lib/common.sh"; . "$REPO/modules/06-react-atlas.sh"
  run_in() { :; }; json_merge_mcp() { :; }; codex_mcp_add() { :; }
  mkdir -p "$HOME/.claude"
  printf 'top\n<!-- react_atlas:start -->\nold\n<!-- react_atlas:end -->\nbottom\n' >"$HOME/.claude/CLAUDE.md"
  react_atlas_install
  assert_eq "$(cat "$HOME/.claude/CLAUDE.md")" "$(printf 'top\nbottom')"
}

test_codex_mcp_registration_lines_in_dry_run() {
  b="$HOME/bin"; mkdir -p "$b"; printf '#!/bin/sh\nexit 1\n' >"$b/codex"; chmod +x "$b/codex"
  out="$(PATH="$b:$PATH" "$REPO/setup" --only react-atlas,qa-engineer --dry-run)"
  assert_contains "$out" "+ codex mcp add react_atlas -- react-atlas server"
  assert_contains "$out" "+ codex mcp add qa-engineer -- $HOME/.local/bin/qa-engineer mcp"
}

test_codex_mcp_add_skips_when_present_or_codex_missing() {
  . "$REPO/lib/common.sh"
  b="$HOME/bin"; mkdir -p "$b"
  { echo '#!/bin/sh'; echo "echo \"\$*\" >>\"$HOME/calls\""; } >"$b/codex"; chmod +x "$b/codex"
  PATH="$b:$PATH" codex_mcp_add x -- cmd
  assert_eq "$(cat "$HOME/calls")" "mcp get x"
  has() { return 1; }
  codex_mcp_add y cmd
  assert_eq "$(wc -l <"$HOME/calls" | tr -d ' ')" "1"
}

test_every_repo_skill_has_a_routing_rule() {
  for s in "$REPO"/skills/*/; do
    s="${s%/}"; grep -q "\`${s##*/}\`" "$REPO/rules/skills.md" || { echo "no rule for ${s##*/} in rules/skills.md" >&2; return 1; }
  done
}
